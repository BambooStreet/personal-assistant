-- 반복 할 일의 트리거("일어나자마자" / "이동 간" / "자기 전" …).
--
-- 리디자인의 핵심 판단: 반복 할 일에서 중요한 건 빈도가 아니라 **어떤 상황에서 하는가**다.
-- 그래서 화면에서 '매일/매주/매월' 선택을 없애고 트리거를 고르게 한다(매일이 전제).
--
-- ⚠️ `recur`를 대체하지 않는다. recur는 완료 시 다음 발생으로 전진시키는 Core 로직
-- (`commands/todos.rs::next_occurrence`)의 입력이라 계속 필요하다 — 반복 할 일은
-- recur='daily'로 두고, trigger_slot은 표시·정렬용으로 그 위에 얹는다.
--
-- 이건 goal_routines(요일 비트마스크 + 시각 한 점 → OS 알림)와는 **별개**다. 그쪽 모델을
-- 트리거로 바꾸는 건 배포된 알림을 건드리는 별도 작업이다.
--
-- 컬럼명이 `trigger`가 아닌 이유: SQLite 예약어라 쓸 때마다 따옴표가 필요하다.

ALTER TABLE todos ADD COLUMN trigger_slot TEXT;
